export function parseSpawn(levels, probs) {
  const out = {};
  const L = String(levels || '').split(',').map((s) => s.trim()).filter(Boolean);
  const Pr = String(probs || '').split(',').map((s) => s.trim());
  L.forEach((l, i) => { const n = Number(l); if (!Number.isNaN(n)) out[n] = Number(Pr[i] ?? 0) || 0; });
  return out;
}

